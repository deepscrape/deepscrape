/**
 * Guard the FUNCTIONS_ENV_JSON publish.
 *
 * The secret is one version of one JSON blob, and every consumer (Functions and
 * the BFF, which mounts it by name) reads whatever version is latest. Publishing
 * is a whole-file replace, so a partial source silently *deletes* keys: the
 * 11-key `functions/.env` that the merge workflow writes for deploy analysis
 * would, if published, overwrite the live secret and take the platform to
 * "everything unconfigured". There is no merge, no diff, no undo.
 *
 * The invariant this enforces, both before a publish and against production:
 *   the key set must never shrink.
 *
 * Names only. This script never prints, logs or compares a value.
 *
 * Usage
 *   node scripts/check-env-json.cjs                 # validate .deploy-secrets.json
 *   node scripts/check-env-json.cjs --live          # validate the live secret
 *   node scripts/check-env-json.cjs --generate      # rewrite env-keys.json
 *   node scripts/check-env-json.cjs --json <file>   # validate another payload
 *   node scripts/check-env-json.cjs --allow-drop K1,K2   # accept removals
 */
const fs = require("node:fs")
const path = require("node:path")
const {spawnSync} = require("node:child_process")

const rootDir = path.resolve(__dirname, "..")
const manifestPath = path.resolve(rootDir, "env-keys.json")
const defaultPayload = path.resolve(rootDir, ".deploy-secrets.json")
const SECRET_NAME = "FUNCTIONS_ENV_JSON"

const argv = process.argv.slice(2)
const flag = (name) => argv.includes(name)
const value = (name) => {
  const i = argv.indexOf(name)
  return i >= 0 && argv[i + 1] && !argv[i + 1].startsWith("--") ? argv[i + 1] : null
}

/** Keys only: the object is parsed to enumerate them, never to report anything. */
const keysOfJson = (text) => Object.keys(JSON.parse(text) || {}).sort()

const keysOfFile = (file) => keysOfJson(fs.readFileSync(file, "utf8"))

const walkSource = (dir) => fs.readdirSync(dir, {withFileTypes: true}).flatMap((e) => {
  const p = path.join(dir, e.name)
  if (e.isDirectory()) {
    return walkSource(p)
  }
  return e.isFile() && p.endsWith(".ts") && !p.endsWith(".spec.ts") ? [p] : []
})

/** `getConfigValue("X")` with no fallback means the code cannot run without it. */
const requiredKeys = () => {
  const found = new Set()
  for (const file of walkSource(path.join(rootDir, "src"))) {
    const src = fs.readFileSync(file, "utf8")
    for (const m of src.matchAll(/getConfigValue\(\s*"([A-Za-z0-9_]+)"\s*\)/g)) {
      found.add(m[1])
    }
  }
  return [...found].sort()
}

const liveKeys = () => {
  const result = spawnSync(
    "gcloud",
    ["secrets", "versions", "access", "latest", "--secret", SECRET_NAME],
    {encoding: "utf8"},
  )

  if (result.status !== 0) {
    console.error(`cannot read ${SECRET_NAME}: ${(result.stderr || "").trim()}`)
    console.error("authenticate with gcloud, or drop --live")
    process.exit(2)
  }

  return keysOfJson(result.stdout)
}

const readManifest = () => {
  if (!fs.existsSync(manifestPath)) {
    return null
  }
  return JSON.parse(fs.readFileSync(manifestPath, "utf8"))
}

const writeManifest = (payloadKeys) => {
  const manifest = {
    comment: "Key NAMES only, generated by scripts/check-env-json.cjs --generate. " +
      "Never put a value here.",
    secret: SECRET_NAME,
    keys: payloadKeys,
  }
  fs.writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`)
  console.log(`wrote ${path.basename(manifestPath)} with ${payloadKeys.length} keys`)
}

const allowDrop = new Set(
  (value("--allow-drop") || "").split(",").map((k) => k.trim()).filter(Boolean),
)

const source = flag("--live") ? `${SECRET_NAME} (live)` : (value("--json") || defaultPayload)

if (!flag("--live") && !fs.existsSync(source)) {
  console.error(`no payload to check: ${source}`)
  console.error("run npm run migrate:env:json first, or pass --live")
  process.exit(2)
}

const keys = flag("--live") ? liveKeys() : keysOfFile(source)

if (flag("--generate")) {
  writeManifest(keys)
  process.exit(0)
}

const manifest = readManifest()
if (!manifest || !Array.isArray(manifest.keys)) {
  console.error(`missing ${path.basename(manifestPath)}: run --generate once and commit it`)
  process.exit(2)
}

const dropped = manifest.keys.filter((k) => !keys.includes(k) && !allowDrop.has(k))
const added = keys.filter((k) => !manifest.keys.includes(k))
const absentRequired = requiredKeys().filter((k) => !keys.includes(k))

console.log(`${source}: ${keys.length} keys (manifest expects ${manifest.keys.length})`)

if (added.length) {
  // Growth is fine and is how a new key ships; the manifest catches up on the
  // next --generate, which puts the addition in the diff for review.
  console.log(`  new since manifest (${added.length}): ${added.join(", ")}`)
}

if (absentRequired.length) {
  // Informational. These are keys the code reads without a fallback but that the
  // live blob legitimately does not carry (unused vendors, the *_TEST pair that
  // lives in its own secret, the twin WEBRAIN_MCP_TOKEN). Failing on them would
  // block every merge for state that predates this guard.
  console.log(`  read without fallback, not in this set (${absentRequired.length}): ${absentRequired.join(", ")}`)
}

if (dropped.length) {
  console.error(`\nREFUSING: this would REMOVE ${dropped.length} key(s) production has:`)
  console.error(`  ${dropped.join("\n  ")}`)
  console.error("\nA publish replaces the whole secret. If the removal is intended,")
  console.error("regenerate the manifest in the same commit: --generate")
  console.error("or accept it once: --allow-drop " + dropped.join(","))
  process.exit(1)
}

console.log("ok: no key was dropped")
